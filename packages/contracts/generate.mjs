import { compileFromFile } from "json-schema-to-typescript";
import { spawnSync } from "node:child_process";
import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "../..");
const schemaDir = resolve(here, "schemas");
const tsDir = resolve(root, "apps/web/src/types");
const pyDir = resolve(here, "src/contracts/generated");
const banner = "/* Generated by packages/contracts/generate.mjs. Do not edit. */";

function collectRefs(value, refs) {
  if (Array.isArray(value)) {
    for (const item of value) collectRefs(item, refs);
    return;
  }
  if (value && typeof value === "object") {
    if (typeof value.$ref === "string") {
      const file = value.$ref.split("#")[0];
      if (file) refs.add(file);
    }
    for (const child of Object.values(value)) collectRefs(child, refs);
  }
}

function readSchema(name) {
  return JSON.parse(readFileSync(resolve(schemaDir, name), "utf8"));
}

async function generateTypeScript(schemaFiles, titles) {
  rmSync(tsDir, { recursive: true, force: true });
  mkdirSync(tsDir, { recursive: true });

  const exports = [];
  for (const name of schemaFiles) {
    const refs = new Set();
    collectRefs(readSchema(name), refs);
    const imports = [...refs]
      .sort()
      .map((ref) => {
        const title = titles.get(ref);
        if (!title) throw new Error(`${name} references unknown schema ${ref}`);
        const moduleName = ref.replace(/\.json$/, "");
        return `import type { ${title} } from "./${moduleName}.ts";`;
      })
      .join("\n");

    const body = await compileFromFile(resolve(schemaDir, name), {
      bannerComment: "",
      format: true,
      declareExternallyReferenced: false,
      enableConstEnums: false,
      additionalProperties: false,
      unknownAny: true,
    });

    const moduleName = name.replace(/\.json$/, "");
    const parts = [banner];
    if (imports) parts.push("", imports);
    parts.push("", body.trimEnd(), "");
    writeFileSync(resolve(tsDir, `${moduleName}.ts`), parts.join("\n"));
    exports.push(`export type { ${titles.get(name)} } from "./${moduleName}.ts";`);
  }

  writeFileSync(resolve(tsDir, "index.ts"), `${banner}\n\n${exports.join("\n")}\n`);
}

function generatePython() {
  rmSync(pyDir, { recursive: true, force: true });
  const result = spawnSync(
    "uv",
    [
      "run",
      "datamodel-codegen",
      "--input",
      schemaDir,
      "--input-file-type",
      "jsonschema",
      "--output",
      pyDir,
      "--output-model-type",
      "pydantic_v2.BaseModel",
      "--target-python-version",
      "3.12",
      "--formatters",
      "builtin",
      "--disable-timestamp",
      "--use-default",
      "--use-double-quotes",
      "--use-title-as-name",
      "--enum-field-as-literal",
      "all",
      "--extra-fields",
      "forbid",
      "--field-constraints",
      "--collapse-root-models",
      "--reuse-model",
      "--keep-model-order",
      "--use-tuple-for-fixed-items",
      "--strict-nullable",
      "--use-exact-imports",
    ],
    { cwd: root, stdio: "inherit" },
  );
  if (result.status !== 0) {
    process.exit(result.status ?? 1);
  }
}

const schemaFiles = readdirSync(schemaDir)
  .filter((name) => name.endsWith(".json"))
  .sort();
const titles = new Map(
  schemaFiles.map((name) => {
    const title = readSchema(name).title;
    if (typeof title !== "string") throw new Error(`${name} is missing a title`);
    return [name, title];
  }),
);

await generateTypeScript(schemaFiles, titles);
generatePython();
